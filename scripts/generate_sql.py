"""Generates schema.sql (MySQL DDL) and sample_data.sql by running the real services
against a throw-away SQLite DB, so the sample data is always consistent with the app logic.
Usage:  BCRYPT_ROUNDS=12 python scripts/generate_sql.py
"""
import enum
import sys
from datetime import datetime, timedelta
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from sqlalchemy import create_engine, select
from sqlalchemy.dialects import mysql
from sqlalchemy.orm import sessionmaker
from sqlalchemy.pool import StaticPool
from sqlalchemy.schema import CreateIndex, CreateTable

from app import models as m
from app.database import Base
from app.security import hash_password
from app.services import order_service, product_service, stock_service
from app.services.base import transaction

ROOT = Path(__file__).resolve().parent.parent
dialect = mysql.dialect()

# ---------- schema.sql ----------
ddl = ["-- StockFlow MySQL schema (generated by scripts/generate_sql.py)",
       "CREATE DATABASE IF NOT EXISTS stockflow CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;",
       "USE stockflow;", ""]
for t in Base.metadata.sorted_tables:
    ddl.append(str(CreateTable(t).compile(dialect=dialect)).strip() + ";")
    for ix in sorted(t.indexes, key=lambda i: i.name):
        ddl.append(str(CreateIndex(ix).compile(dialect=dialect)).strip() + ";")
    ddl.append("")
(ROOT / "schema.sql").write_text("\n".join(ddl))

# ---------- seed via services ----------
engine = create_engine("sqlite://", connect_args={"check_same_thread": False}, poolclass=StaticPool)
Base.metadata.create_all(engine)
db = sessionmaker(bind=engine, autoflush=False)()

users = {}
for name, role, pw in (("admin", m.Role.ADMIN, "Admin@123"), ("manager", m.Role.MANAGER, "Manager@123"), ("staff", m.Role.STAFF, "Staff@1234")):
    u = m.User(username=name, email=f"{name}@stockflow.test", hashed_password=hash_password(pw), role=role)
    db.add(u)
    users[name] = u
db.commit()

cats = {n: m.Category(name=n, description=d) for n, d in (
    ("Electronics", "Gadgets and accessories"), ("Stationery", "Office and school supplies"),
    ("Furniture", "Desks, chairs and storage"), ("Groceries", "Pantry items"))}
sups = {n: m.Supplier(name=n, email=e, phone=p, address=a) for n, e, p, a in (
    ("TechSource Pvt Ltd", "sales@techsource.example", "+91 44 2345 6789", "12 Anna Salai, Chennai"),
    ("PaperWorld", "orders@paperworld.example", "+91 80 4000 1111", "5 MG Road, Bengaluru"),
    ("HomeNest Furnishings", "hello@homenest.example", "+91 22 5555 2222", "88 Link Road, Mumbai"))}
db.add_all([*cats.values(), *sups.values()])
db.commit()

catalog = [  # sku, name, price, category, supplier, reorder, initial stock
    ("ELE-001", "Wireless Mouse", "799.00", "Electronics", "TechSource Pvt Ltd", 15, 80),
    ("ELE-002", "USB-C Cable 1m", "299.00", "Electronics", "TechSource Pvt Ltd", 25, 200),
    ("ELE-003", "Bluetooth Speaker", "2499.00", "Electronics", "TechSource Pvt Ltd", 10, 8),
    ("STA-001", "A4 Notebook (200 pages)", "120.00", "Stationery", "PaperWorld", 30, 150),
    ("STA-002", "Ball Pen Pack (10)", "80.00", "Stationery", "PaperWorld", 40, 25),
    ("STA-003", "Desk Organiser", "450.00", "Stationery", "PaperWorld", 10, 40),
    ("FUR-001", "Ergonomic Chair", "7999.00", "Furniture", "HomeNest Furnishings", 5, 12),
    ("FUR-002", "Standing Desk", "15999.00", "Furniture", "HomeNest Furnishings", 3, 4),
    ("GRO-001", "Filter Coffee 500g", "399.00", "Groceries", None, 20, 60),
    ("GRO-002", "Green Tea (100 bags)", "349.00", "Groceries", None, 20, 0),
]
pid = {}
for sku, name, price, cat, sup, reorder, stock in catalog:
    p = product_service.create_product(db, {"sku": sku, "name": name, "price": price, "category_id": cats[cat].id,
                                            "supplier_id": sups[sup].id if sup else None, "reorder_level": reorder, "description": None})
    pid[sku] = p.id
    if stock:
        stock_service.stock_in(db, {"product_id": p.id, "quantity": stock, "reference": "OPENING-STOCK", "note": None}, users["manager"].id)

stock_service.stock_out(db, {"product_id": pid["STA-002"], "quantity": 5, "reference": "ADJ-1", "note": "Damaged in storage"}, users["manager"].id)

orders = [
    ("Ravi Traders", "staff", [("ELE-001", 10), ("ELE-002", 20)], 6),
    ("Meena Stores", "staff", [("STA-001", 30), ("STA-002", 10)], 4),
    ("Chennai Office Hub", "manager", [("FUR-001", 3), ("FUR-002", 1)], 3),
    ("Ravi Traders", "staff", [("GRO-001", 12), ("ELE-003", 2)], 1),
    ("Test Cancelled Order", "staff", [("STA-003", 5)], 1),
]
created = []
for cust, who, items, days_ago in orders:
    o = order_service.create_order(db, {"customer_name": cust, "items": [{"product_id": pid[s], "quantity": q} for s, q in items]}, users[who])
    created.append((o, days_ago))
order_service.update_status(db, created[0][0].id, m.OrderStatus.COMPLETED, users["manager"])
order_service.update_status(db, created[1][0].id, m.OrderStatus.COMPLETED, users["manager"])
order_service.update_status(db, created[4][0].id, m.OrderStatus.CANCELLED, users["manager"])

# spread order dates so the sales-by-day report is interesting
with transaction(db):
    for o, days in created:
        o.created_at = datetime(2026, 10, 26, 10, 30) - timedelta(days=days)
    for mv in db.scalars(select(m.StockMovement).where(m.StockMovement.order_id.is_not(None))):
        mv.created_at = db.get(m.Order, mv.order_id).created_at


# ---------- sample_data.sql ----------
def lit(v):
    if v is None:
        return "NULL"
    if isinstance(v, enum.Enum):
        v = v.value
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, (int, float)) or hasattr(v, "as_tuple"):
        return str(v)
    if isinstance(v, datetime):
        v = v.strftime("%Y-%m-%d %H:%M:%S")
    return "'" + str(v).replace("\\", "\\\\").replace("'", "''") + "'"


out = ["-- StockFlow sample data (generated by scripts/generate_sql.py)",
       "-- Logins: admin / Admin@123,  manager / Manager@123,  staff / Staff@1234",
       "USE stockflow;", "SET FOREIGN_KEY_CHECKS = 0;", ""]
for t in Base.metadata.sorted_tables:
    rows = db.execute(select(t).order_by(t.c.id)).all()
    cols = ", ".join(f"`{c.name}`" for c in t.columns)
    out.append(f"-- {t.name} ({len(rows)} rows)")
    for r in rows:
        out.append(f"INSERT INTO `{t.name}` ({cols}) VALUES ({', '.join(lit(v) for v in r)});")
    out.append("")
out.append("SET FOREIGN_KEY_CHECKS = 1;")
(ROOT / "sample_data.sql").write_text("\n".join(out) + "\n")
print("Generated schema.sql and sample_data.sql")
